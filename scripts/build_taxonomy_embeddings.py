#!/usr/bin/env python3
"""Generate db/seed/taxonomy_embeddings.sql and the cross-language golden
probe file for the FR-09/TECH-09 linking stack.

Reads db/seed/taxonomy.sql (the governed taxonomy seed), embeds every
non-sensitive, non-redirect node with ngram-hash-384.v1, and writes:

  - db/seed/taxonomy_embeddings.sql      — idempotent INSERTs, run after
    the 0011_linking migration (mounted as 13_ in deploy);
  - services/edge/test/golden_embeddings.json — fixed probe vectors the
    TypeScript embedder is pinned against (and this generator in turn).

Both outputs are deterministic: same taxonomy seed, same bytes.

Run: python3 scripts/build_taxonomy_embeddings.py
"""

from __future__ import annotations

import ast
import json
import re
from pathlib import Path

from taxonomy_embedder import DIMS, EMBEDDER_ID, embed, node_text

ROOT = Path(__file__).resolve().parent.parent
TAXONOMY_SQL = ROOT / "db/seed/taxonomy.sql"
SEED_OUT = ROOT / "db/seed/taxonomy_embeddings.sql"
GOLDEN_OUT = ROOT / "services/edge/test/golden_embeddings.json"

# Probe strings exercise multi-token overlap, partial overlap and none.
PROBES = [
    "jazz and climbing",
    "premier league football",
    "vegan street food",
    "afrobeats and live music",
    "quiet coffee and a book",
]

NODE_ROW = re.compile(
    r"INSERT INTO taxonomy_nodes \(node_id, label, parent_id, kind, sensitive, redirect_to, depth\) VALUES (\(.*?\)) ON CONFLICT"
)


def parse_nodes() -> list[tuple[str, str, bool, bool]]:
    """(node_id, label, sensitive, has_redirect) tuples from the seed."""
    out: list[tuple[str, str, bool, bool]] = []
    for match in NODE_ROW.finditer(TAXONOMY_SQL.read_text()):
        python_tuple = (
            match.group(1).replace("NULL", "None").replace("true", "True").replace("false", "False")
        )
        node_id, label, _parent, _kind, sensitive, redirect_to, _depth = ast.literal_eval(python_tuple)
        out.append((node_id, label, sensitive, redirect_to is not None))
    return out


def vector_literal(vec: list[float]) -> str:
    return "[" + ",".join(repr(float(x)) for x in vec) + "]"


def main() -> None:
    nodes = parse_nodes()
    embeddable = [(nid, label) for nid, label, sensitive, redirected in nodes if not sensitive and not redirected]

    lines = [
        "-- Generated by scripts/build_taxonomy_embeddings.py — do not edit by hand.",
        f"-- embedder: {EMBEDDER_ID}, dims: {DIMS}, nodes: {len(embeddable)}",
        "-- FR-09/TECH-09: pgvector search space for free-text linking; sensitive",
        "-- and redirected nodes are excluded at seed time as well as at query time.",
        "BEGIN;",
    ]
    for node_id, label in embeddable:
        vec = embed(node_text(node_id, label))
        safe_id = node_id.replace("'", "''")
        lines.append(
            f"INSERT INTO taxonomy_node_embeddings (node_id, embedding, embedder) VALUES "
            f"('{safe_id}', '{vector_literal(vec)}'::vector, '{EMBEDDER_ID}') "
            f"ON CONFLICT (node_id) DO UPDATE SET embedding = EXCLUDED.embedding, "
            f"embedder = EXCLUDED.embedder, updated_at = now();"
        )
    lines.append("COMMIT;")
    SEED_OUT.write_text("\n".join(lines) + "\n")

    golden = {
        "embedder": EMBEDDER_ID,
        "dims": DIMS,
        "probes": {probe: embed(probe) for probe in PROBES},
    }
    GOLDEN_OUT.write_text(json.dumps(golden, indent=1) + "\n")

    print(f"nodes parsed: {len(nodes)}, embedded: {len(embeddable)}")
    print(f"wrote {SEED_OUT.relative_to(ROOT)} and {GOLDEN_OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
